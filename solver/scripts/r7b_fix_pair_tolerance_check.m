function result=r7b_fix_pair_tolerance_check(root,sample,variant,water)
%R7B_FIX_PAIR_TOLERANCE_CHECK Four real fixed-parameter tolerance re-solves.
% Only preselected S1/M3/0.18 and S5/M3/10 are in scope. Called on the
% root's existing serial LiveLink connection; never starts/connects COMSOL.
% Reuses accepted state checkpoints from r7b_fix_tolerance_check, including
% the EXACT H_background selected by kappa_frozen. No re-calibration occurs.
% A final comparison.json is written only when all four actual strict
% solves have succeeded, their saved MPH files exist, and state identities,
% unchanged parameters, mesh, flux and energy checks pass.
% Example: r7b_fix_pair_tolerance_check(root,'S1','M3',.18)
if nargin<1||isempty(root),root=fileparts(fileparts(mfilename('fullpath')));end
assert(nargin==4,'Specify root, sample, M3, fluid conductivity');
sample=char(sample);variant=char(variant);
assert(strcmp(variant,'M3') && ((strcmp(sample,'S1')&&water==.18)||(strcmp(sample,'S5')&&water==10)),...
 'Only the two preselected S1/M3/0.18 and S5/M3/10 pairs may be checked');
out=fullfile(root,'runs','round7b_localfit');
waterToken=['water_' strrep(sprintf('%.10g',water),'.','p')];
wf=fullfile(out,'states',[sample '_' variant],waterToken);
frozenPath=fullfile(wf,'kappa_frozen.json');pairPath=fullfile(wf,'PAIR_SUCCESS.json');
assert(isfile(frozenPath)&&isfile(pairPath),'Complete actual pair and background freeze are required first');
frozen=jsondecode(fileread(frozenPath));pair=jsondecode(fileread(pairPath));
assert(strcmp(frozen.status,'FROZEN_BEFORE_TARGETS')&&strcmp(pair.status,'success'),'Source pair/freeze is incomplete');
assert(strcmp(frozen.sample,sample)&&strcmp(frozen.input_variant,variant)&&frozen.fluid_and_fracture_sigma_S_m==water,...
 'Frozen background identity mismatch');
assert(strcmp(pair.sample,sample)&&strcmp(pair.input_variant,variant)&&pair.water_sigma_S_m==water,'Saved pair identity mismatch');
assert(frozen.skeleton_sigma_S_m==1e-5&&isfinite(frozen.kappa_eq_S_m)&&frozen.kappa_eq_S_m>0,...
 'Invalid actual frozen material parameters');
input=fullfile(out,'inputs',[sample '_' variant]);
geometryPath=fullfile(input,'geometry_ready.mph');
assert(isfile(fullfile(input,'GEOMETRY_SUCCESS.json'))&&isfile(geometryPath),'Accepted fixed geometry missing');
sel=jsondecode(fileread(fullfile(input,'selections.json')));
roles={'T_background','H_background','T_target','H_target'};
paths={fullfile(wf,'T_background','SUCCESS.json'),frozen.H_background_success_json,...
 fullfile(wf,'T_target','SUCCESS.json'),fullfile(wf,'H_target','SUCCESS.json')};
assert(startsWith(lower(canonical_path(paths{2})),[lower(canonical_path(fullfile(wf,'calibration'))) filesep]),...
 'Selected H background must belong to this exact new local-fit pair');
states=cell(1,4);oldG=zeros(1,4);oldTol=zeros(1,4);strictTol=zeros(1,4);oldModelPaths=cell(1,4);
for k=1:4
 assert(isfile(paths{k}),'Missing actual saved %s',roles{k});
 paths{k}=canonical_path(paths{k});
 s=jsondecode(fileread(paths{k}));states{k}=s;
 assert(strcmp(s.status,'success')&&strcmp(s.sample,sample)&&strcmp(s.input_variant,variant)&&s.water_sigma_S_m==water,...
  'Actual saved %s has wrong identity/status',roles{k});
 expectedState=roles{k};if k==2,expectedState='H_calibration';end
 assert(strcmp(s.state,expectedState)&&s.fracture_on==double(k>=3)&&s.H_on==double(mod(k,2)==0),...
  'Saved %s state flags mismatch',roles{k});
 assert(logical(s.formal_CT_target)==logical(k>=3)&&s.skeleton_sigma_S_m==frozen.skeleton_sigma_S_m,...
  'Saved %s physical scope mismatch',roles{k});
 assert(isfinite(s.G_S)&&s.G_S>0,'Missing/nonfinite actual response in %s',roles{k});
 assert(s.vertices==sel.vertices&&s.tetrahedra==sel.tetrahedra,'Saved %s uses a different mesh',roles{k});
 assert(strcmpi(canonical_path(s.geometry_model_path),canonical_path(geometryPath)),'Saved %s geometry path mismatch',roles{k});
 assert(isfile(s.model_path)&&strcmpi(canonical_path(s.model_path),canonical_path(fullfile(fileparts(paths{k}),'solution.mph'))),...
  'Saved %s does not name its own actual solution MPH',roles{k});
 if k~=1
  assert(abs(log(s.kappa_S_m/frozen.kappa_eq_S_m))<1e-12,'Saved %s changed frozen kappa',roles{k});
 else
  assert(s.kappa_S_m==s.skeleton_sigma_S_m,'Unexpected original inactive kappa in T background');
 end
 oldG(k)=s.G_S;oldTol(k)=s.stationary_relative_tolerance;oldModelPaths{k}=s.model_path;
 if abs(log10(oldTol(k))+8)<1e-9,strictTol(k)=1e-10;
 elseif abs(log10(oldTol(k))+10)<1e-9,strictTol(k)=1e-11;
 else,error('Saved state tolerance is outside the declared bounded check');end
end
assert(strcmpi(canonical_path(oldModelPaths{2}),canonical_path(frozen.H_background_solution_mph)),...
 'H background source MPH differs from frozen selection');
assert(relative_close(oldG(1),frozen.G0_T_S)&&relative_close(oldG(2),frozen.G0_H_S),'Actual background states differ from freeze');
oldGain=[oldG(3)-oldG(1),oldG(4)-oldG(2)];oldDelta=oldGain(2)-oldGain(1);
assert(relative_close(oldGain(1),pair.gT_S)&&relative_close(oldGain(2),pair.gH_S),...
 'Saved pair gains differ from its own actual four states');
assert(relative_close(oldG(3),pair.Gf_T_S)&&relative_close(oldG(4),pair.Gf_H_S),'Saved pair targets differ from actual states');
folder=fullfile(out,'tolerance_checks',sprintf('%s_%s_%s_pair_four_states',sample,variant,waterToken));
if ~isfolder(folder),mkdir(folder);end
done=fullfile(folder,'comparison.json');
if isfile(done)
 result=jsondecode(fileread(done));
 assert(strcmp(result.status,'success')&&result.all_four_state_checks_completed&&result.applies_to_pair_difference,...
  'Existing pair tolerance comparison is incomplete');
 assert(strcmp(result.sample,sample)&&strcmp(result.input_variant,variant)&&result.water_sigma_S_m==water,...
  'Existing tolerance pair identity mismatch');
 assert(isequal(reshape(result.old_G_by_role_S,1,[]),oldG)&&isequal(reshape(result.strict_stationary_tolerances,1,[]),strictTol),...
  'Existing tolerance comparison belongs to changed source states');
 assert(numel(result.evidence_model_paths)==8&&all(cellfun(@isfile,result.evidence_model_paths)),...
  'Some actual old/strict evidence MPH files are missing');
 fprintf('R7BFIX_PAIR_TOLERANCE_REUSE %s\n',done);return;
end
request=struct('schema','r7b_localfit_preselected_pair_tolerance_request_v1','sample',sample,'input_variant',variant,...
 'water_sigma_S_m',water,'source_pair_json',canonical_path(pairPath),'source_kappa_frozen_json',canonical_path(frozenPath),...
 'kappa_eq_S_m',frozen.kappa_eq_S_m,'source_state_roles',{roles},'source_state_success_jsons',{paths},...
 'source_model_paths',{oldModelPaths},'old_G_by_role_S',oldG,'old_stationary_tolerances',oldTol,...
 'strict_stationary_tolerances',strictTol,'state_count_required',4,'all_four_state_checks_completed',false,...
 'observed_gain_or_pair_change_scale_S',NaN,'strict_delta_gH_minus_gT_S',NaN,...
 'fixed_geometry_model_path',geometryPath,'vertices',sel.vertices,'tetrahedra',sel.tetrahedra,...
 'background_kappa_recalibrated',false,'new_scientific_targets',0,'main_state_files_overwritten',false,...
 'rule','Re-solve the four already-completed states with tighter tolerance only; use the sum of their absolute conductance changes as an observed pair-difference scale, not a rigorous error bound');
r3_json(fullfile(folder,'request_before_checks.json'),request);
strict=cell(1,4);strictG=nan(1,4);strictModelPaths=cell(1,4);strictComparisonPaths=cell(1,4);started=tic;
try
 for k=1:4
  strict{k}=r7b_fix_tolerance_check(root,paths{k},strictTol(k));r=strict{k};
  assert(strcmp(r.status,'success')&&isfile(r.strict_model_path),'Strict %s solve did not complete',roles{k});
  assert(strcmpi(r.source_success_json,paths{k})&&strcmp(r.sample,sample)&&strcmp(r.input_variant,variant)&&r.water_sigma_S_m==water,...
   'Strict %s result is not the requested actual state',roles{k});
  assert(relative_close(r.old_G_S,oldG(k))&&isfinite(r.strict_G_S)&&r.strict_G_S>0,'Strict %s old/new response missing or mismatched',roles{k});
  assert(r.strict_stationary_tolerance==strictTol(k)&&r.vertices==sel.vertices&&r.tetrahedra==sel.tetrahedra,...
   'Strict %s tolerance/mesh mismatch',roles{k});
  assert(isequal(r.parameters_before,r.parameters_after),'Strict %s physical parameters changed',roles{k});
  assert(max(r.reaction_flux_relative_error,r.energy_relative_error)<1e-7,'Strict %s conservation check failed',roles{k});
  assert(r.parameters_after.frac_on==double(k>=3)&&r.parameters_after.H_on==double(mod(k,2)==0),...
   'Strict %s state flags changed',roles{k});
  assert(abs(log(r.parameters_after.kappa/states{k}.kappa_S_m))<1e-12,'Strict %s saved kappa changed',roles{k});
  strictG(k)=r.strict_G_S;strictModelPaths{k}=r.strict_model_path;
  strictComparisonPaths{k}=fullfile(fileparts(r.strict_model_path),'comparison.json');
  assert(isfile(strictComparisonPaths{k}),'Strict %s success record missing',roles{k});
  progress=request;progress.completed_roles=roles(1:k);progress.completed_state_count=k;
  progress.strict_G_by_role_S=strictG;progress.elapsed_seconds=toc(started);
  % Partial progress retains null for unmeasured states and the final scale.
  r3_json(fullfile(folder,'progress.json'),progress);
 end
 assert(all(isfinite(strictG))&&all(cellfun(@isfile,strictModelPaths)),'All four actual strict solves are required');
 strictGain=[strictG(3)-strictG(1),strictG(4)-strictG(2)];strictDelta=strictGain(2)-strictGain(1);
 changes=strictG-oldG;observedScale=sum(abs(changes));
 oldMismatch=oldG(2)-oldG(1);strictMismatch=strictG(2)-strictG(1);
 evidence=[oldModelPaths strictModelPaths];
 result=struct('schema','r7b_localfit_four_state_pair_tolerance_v1','status','success',...
  'sample',sample,'input_variant',variant,'water_sigma_S_m',water,'state_roles',{roles},...
  'all_four_state_checks_completed',true,'completed_state_count',4,'applies_to_pair_difference',true,...
  'source_pair_json',canonical_path(pairPath),'source_kappa_frozen_json',canonical_path(frozenPath),...
  'source_state_success_jsons',{paths},'strict_state_comparison_jsons',{strictComparisonPaths},...
  'old_model_paths',{oldModelPaths},'strict_model_paths',{strictModelPaths},'evidence_model_paths',{evidence},...
  'old_stationary_tolerances',oldTol,'strict_stationary_tolerances',strictTol,...
  'old_G_by_role_S',oldG,'strict_G_by_role_S',strictG,'conductance_changes_by_role_S',changes,...
  'absolute_conductance_changes_by_role_S',abs(changes),...
  'observed_gain_or_pair_change_scale_S',observedScale,'observed_scale_definition','sum of four abs(G_strict - G_old)',...
  'old_gT_S',oldGain(1),'old_gH_S',oldGain(2),'strict_gT_S',strictGain(1),'strict_gH_S',strictGain(2),...
  'gT_change_S',strictGain(1)-oldGain(1),'gH_change_S',strictGain(2)-oldGain(2),...
  'old_delta_gH_minus_gT_S',oldDelta,'strict_delta_gH_minus_gT_S',strictDelta,...
  'delta_strict_minus_delta_old_S',strictDelta-oldDelta,...
  'old_epsilon_delta_over_gT',safe_ratio(oldDelta,oldGain(1)),...
  'strict_epsilon_delta_over_gT',safe_ratio(strictDelta,strictGain(1)),...
  'old_background_match_H_minus_T_S',oldMismatch,'strict_background_match_H_minus_T_S',strictMismatch,...
  'background_match_change_S',strictMismatch-oldMismatch,...
  'old_relative_background_mismatch',oldMismatch/oldG(1),'strict_relative_background_mismatch',strictMismatch/strictG(1),...
  'required_original_background_match_tolerance',frozen.required_relative_tolerance,...
  'strict_background_still_within_original_matching_tolerance',abs(strictMismatch/strictG(1))<=frozen.required_relative_tolerance,...
  'kappa_eq_S_m',frozen.kappa_eq_S_m,'kappa_fixed',true,'background_kappa_recalibrated',false,...
  'fixed_geometry_model_path',geometryPath,'vertices',sel.vertices,'tetrahedra',sel.tetrahedra,...
  'source_geometry_modified',false,'source_materials_or_loading_modified',false,...
  'main_state_files_overwritten',false,'new_scientific_targets',0,...
  'observed_scale_is_rigorous_bound',false,'scope_note',...
  'Measured only for this preselected sample/fluid/M3 pair: four saved actual states are re-solved on the same accepted mesh with their original fixed parameters and frozen H kappa. Sum of four absolute conductance changes is an empirical numerical scale for the gain difference, not a guaranteed error bound or evidence for every other state. Background matching changes are reported without recalibration.',...
  'total_seconds',toc(started),'completed_local',char(datetime('now','Format','yyyy-MM-dd HH:mm:ss')));
 rows=cell(4,8);
 for k=1:4,rows(k,:)={roles{k},oldTol(k),strictTol(k),oldG(k),strictG(k),changes(k),paths{k},strictModelPaths{k}};end
 writetable(cell2table(rows,'VariableNames',{'state_role','old_tolerance','strict_tolerance','old_G_S','strict_G_S','change_S','source_success_json','strict_model_path'}),...
  fullfile(folder,'four_state_tolerance_comparison.csv'));
 r3_json(done,result);
 fprintf('R7BFIX_PAIR_TOLERANCE_COMPLETE %s %s water %.8g scale %.12g delta_change %.12g\n',...
  sample,variant,water,observedScale,strictDelta-oldDelta);
catch ME
 r3_json(fullfile(folder,['FAILED_' char(datetime('now','Format','yyyyMMdd_HHmmss_SSS')) '.json']),...
  struct('status','FOUR_STATE_CHECK_INCOMPLETE','sample',sample,'input_variant',variant,'water_sigma_S_m',water,...
  'strict_G_by_role_S',strictG,'completed_state_count',nnz(isfinite(strictG)),...
  'observed_gain_or_pair_change_scale_S',NaN,'strict_delta_gH_minus_gT_S',NaN,...
  'applies_to_pair_difference',false,'message',ME.message,'identifier',ME.identifier,...
  'report',getReport(ME,'extended','hyperlinks','off'),'main_state_files_overwritten',false));
 rethrow(ME);
end
end

function p=canonical_path(path),f=javaObject('java.io.File',path);p=char(f.getCanonicalPath());end
function yes=relative_close(a,b),yes=isnumeric(a)&&isnumeric(b)&&isscalar(a)&&isscalar(b)&&isfinite(a)&&isfinite(b)&&abs(a-b)<=1e-12*max([abs(a),abs(b),realmin]);end
function v=safe_ratio(a,b),v=NaN;if isfinite(a)&&isfinite(b)&&b~=0,v=a/b;end,end
